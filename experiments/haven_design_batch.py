#!/usr/bin/env python3
"""Run selected coverage arms against fixed, prevalidated Stage-1 artifacts.

There is no Stage-1 generation or repair path in this experiment entry point.
Each failed attempt remains on disk; one failure does not discard later designs.
"""
import backend_imports
import argparse
import json
import os
import re
from concurrent.futures import FIRST_COMPLETED, ThreadPoolExecutor, wait
from pathlib import Path
import sys
import threading
import time

from design_inventory import DESIGNS
from frozen_stage1 import load_fixed_setup, verify_fixed_setup
from rvprobe.backend.process import run
from run_records import framework_hashes, fresh_directory, save, utc
from batch_lifecycle import current_owner
from framework_runtime import runtime_hashes

ROOT = Path(__file__).resolve().parent.parent


def bounded_designs(names, worker, jobs, admit=lambda active: None):
    """A slot includes archival. Stop admission on storage failure, drain live jobs."""
    pending = list(names)
    active = {}
    stopped = None
    with ThreadPoolExecutor(max_workers=jobs) as pool:
        while pending or active:
            while pending and len(active) < jobs and not stopped:
                try:
                    admit(len(active))
                except OSError as error:
                    if not active:
                        stopped = str(error)
                    break
                name = pending.pop(0)
                active[pool.submit(worker, name)] = name
            if not active:
                break
            done, _ = wait(active, return_when=FIRST_COMPLETED)
            for future in done:
                del active[future]
                error = future.result()
                if error:
                    stopped = error
    return pending, stopped


def archive_design(directory, archive, terminal_record, relocate_completed):
    from experiment_storage import archive_tree
    from prune_archived_caches import relocate, validate
    # This record also covers failures before a paired summary was created.
    if terminal_record['status'] not in ('completed', 'failed'):
        raise ValueError('cannot archive a nonterminal design')
    marker = Path('design-result.json')
    save(directory / marker, terminal_record)
    archive_tree(directory, archive)
    if relocate_completed:
        relocate(directory, archive, marker)
    else:
        validate(directory, archive, marker)


def require_frozen_stage1(designs, ready):
    missing = sorted(set(designs) - set(ready))
    if missing:
        raise ValueError('coverage experiments require frozen shared Stage-1 records for: '
                         + ', '.join(missing) + '; this runner cannot generate or repair Stage 1')


def pilot_health(directory, reference, design, status, stop_file):
    """Gate a finished pilot; peers stop only before their next paid request."""
    from stability_campaign import assess, metrics
    try:
        if status != 'completed':
            raise ValueError(design+': pilot failed')
        report=assess([{design:metrics(directory.parent,design)}],
                      {design:metrics(reference,design)},designs=(design,))
    except Exception as error:
        report=dict(passed=False,reasons=[str(error)])
    if not report['passed']:
        try:
            with Path(stop_file).open('x') as stream:
                json.dump(dict(design=design,created_utc=utc(),reasons=report['reasons'],
                    policy='stop-before-next-model-request; never interrupt an in-flight response'),stream)
        except FileExistsError:
            pass  # Preserve the first failing gate and its cause.
    return report


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    for name in ('haven-root', 'env-file', 'out'):
        parser.add_argument('--'+name, required=True, type=Path)
    parser.add_argument('--eda-shell', type=Path, default=ROOT/'experiments/eda-shell')
    parser.add_argument('--designs', nargs='+', choices=DESIGNS, default=list(DESIGNS),
                        help='defaults to the complete 16-design inventory')
    parser.add_argument('--arm', choices=('rvprobe', 'haven', 'both'), default='rvprobe')
    parser.add_argument('--stage1-map',type=Path,required=True,
                        help='design to fixed, passing Stage-1 record; never regenerated by the experiment')
    parser.add_argument('--archive-root',type=Path,help='new durable archive for a volatile working directory')
    parser.add_argument('--jobs',type=int,default=1,help='concurrent designs, including their archival')
    parser.add_argument('--rounds',type=int,default=3,
                        help='coverage rounds forwarded to the selected arm')
    parser.add_argument('--relocate-completed',action='store_true',
                        help='verify archive, then replace finished scratch design with durable symlink')
    parser.add_argument('--generation-map',type=Path,help='design to failed first-round generation to continue')
    parser.add_argument('--encoded-witness-yosys',type=Path,
                        help='explicit bounded auxiliary candidate solver; original native validation remains mandatory')
    parser.add_argument('--encoded-witness-time-limit',default='120s')
    parser.add_argument('--pilot-reference',type=Path)
    parser.add_argument('--stop-new-model-requests',type=Path)
    parser.add_argument('--boundary',choices=['independent-dut-v1'],default='independent-dut-v1')
    import rvprobe_model_options
    rvprobe_model_options.add_options(parser)
    args = parser.parse_args()
    if bool(args.pilot_reference) != bool(args.stop_new_model_requests) or (args.pilot_reference and args.arm!='rvprobe'):
        parser.error('pilot reference and stop flag must be supplied together for the RVProbe arm only')
    if args.pilot_reference and (set(args.designs)-{'uart','ethmac'} or
            not args.stop_new_model_requests.parent.is_dir() or args.stop_new_model_requests.exists()):
        parser.error('pilot gate requires UART/ETHMAC and a new stop flag in an existing directory')
    if not re.fullmatch(r'[1-9][0-9]*s', args.encoded_witness_time_limit):
        parser.error('invalid encoded witness time limit')
    runtime_hashes(ROOT)
    if args.jobs < 1:
        parser.error('--jobs must be positive')
    if args.rounds < 1:
        parser.error('--rounds must be positive')
    if len(args.designs) != len(set(args.designs)):
        parser.error('duplicate designs are not allowed')
    if args.relocate_completed and not args.archive_root:
        parser.error('--relocate-completed requires --archive-root')
    ready = json.loads(args.stage1_map.read_text())
    generations = json.loads(args.generation_map.read_text()) if args.generation_map else {}
    require_frozen_stage1(args.designs, ready)
    fixed = {name:load_fixed_setup(Path(ready[name])) for name in args.designs}
    args.out = args.out.resolve()
    if args.archive_root:
        archive = args.archive_root.resolve()
        if archive == args.out or archive in args.out.parents or args.out in archive.parents:
            parser.error('working and archive roots must be independent')
    fresh_directory(args.out)
    if args.archive_root:
        args.archive_root=args.archive_root.resolve()
        fresh_directory(args.archive_root)
        os.environ['RVPROBE_STORAGE_WORK_ROOT'] = str(args.out)
        os.environ['RVPROBE_STORAGE_ARCHIVE_ROOT'] = str(args.archive_root)
        from experiment_storage import require_space
        require_space(args.out, minimum=1024 * 1024 * 1024)
    began = time.monotonic()
    progress = dict(status='running', started_utc=utc(), pid=os.getpid(), owner=current_owner(), arm=args.arm,
                    model='deepseek-v4-flash-vision-exp', sequences_per_intent=4,
                    rvprobe_generation_options=rvprobe_model_options.record(args),
                    diagnostic_only=False, framework=framework_hashes(ROOT),
                    rounds=args.rounds,
                    shared_setup_mode='frozen', stage1_model_calls=0,
                    fixed_stage1={name:value[1] for name,value in fixed.items()},
                    ready_stage1=ready, continued_generations=generations,
                    jobs=args.jobs,relocate_completed=args.relocate_completed,
                    working_root=str(args.out),archive_root=str(args.archive_root) if args.archive_root else None,
                    boundary=args.boundary or 'shared-environment-conformance-v1',
                    auxiliary_witness_yosys=str(args.encoded_witness_yosys) if args.encoded_witness_yosys else None,
                    auxiliary_witness_time_limit=args.encoded_witness_time_limit,
                    designs={name: {'status':'queued'} for name in args.designs})
    lock = threading.RLock()

    def checkpoint():
        with lock:
            progress['updated_utc']=utc()
            save(args.out/'progress.json',progress)
            if args.archive_root:
                save(args.archive_root/'progress.json',progress)

    def update(item, **fields):
        with lock:
            item.update(fields)
            checkpoint()

    checkpoint()
    tracking = dict(working_root=str(args.out),
                    archive_root=str(args.archive_root) if args.archive_root else None,
                    cohort=('Fixed-Stage-1 continuation cohort' if generations else
                            'Fresh fixed-Stage-1 cohort; no historical replies or continued generations'),
                    attempts={name:[str(args.out/name/'flow/paired/summary.json')] for name in args.designs})
    save(args.out/'tracking.json',tracking)
    if args.archive_root:
        save(args.archive_root/'tracking.json',tracking)

    def command(script, argv, logfile, timeout, temporary):
        env = dict(os.environ, TMPDIR=str(temporary))
        if args.stop_new_model_requests:
            env['RVPROBE_STOP_NEW_MODEL_REQUESTS']=str(args.stop_new_model_requests.resolve())
        with logfile.open('x') as stream:
            result = run([sys.executable, str(ROOT/'experiments'/script), *map(str,argv)],
                         cwd=ROOT, stdout=stream, stderr=-2, timeout=timeout, env=env)
        if result.returncode:
            raise RuntimeError(f'{script} exited {result.returncode}; see {logfile}')

    def experiment(name):
        item = progress['designs'][name]
        directory = args.out/name
        directory.mkdir()
        temporary = directory/'tmp'
        temporary.mkdir(mode=0o700)
        update(item,status='validating_fixed_stage1', started_utc=utc())
        started = time.monotonic()
        try:
            setup, identity = fixed[name]
            verify_fixed_setup(identity)
            cost = Path(ready[name])
            update(item,shared_setup_cost_record=str(cost),
                   prior_shared_setup_usage=setup.get('native_token_tracker'),
                   stage1_model_calls=0,status='running_'+args.arm,stage1=setup['stage1'])
            flow = directory/'flow'
            extra = ['--continue-generation',generations[name]] if name in generations else []
            extra += rvprobe_model_options.cli(args)
            if args.encoded_witness_yosys:
                extra += ['--encoded-witness-yosys', args.encoded_witness_yosys,
                          '--encoded-witness-time-limit', args.encoded_witness_time_limit]
            if args.boundary:
                extra += ['--boundary',args.boundary]
            extra += ['--rounds',str(args.rounds)]
            if identity.get('shared_environment'):
                extra += ['--shared-stage1-environment']
            command('haven_event_paired.py', [
                '--stage1-run',setup['stage1'],'--haven-root',setup['haven_snapshot'],
                '--env-file',args.env_file,'--eda-shell',args.eda_shell,
                '--arm',args.arm,'--out',flow,*extra], directory/'flow.log',13*3600,temporary)
            result = json.loads((flow/'progress.json').read_text())
            update(item,status=result['status'], summary=result.get('summary'), flow=str(flow))
        except Exception as error:
            update(item,status='failed',error=str(error))
        finally:
            try:
                verify_fixed_setup(fixed[name][1])
            except Exception as error:
                update(item,status='failed',fixed_stage1_error=str(error))
            update(item,finished_utc=utc(),elapsed_seconds=time.monotonic()-started)
            if args.pilot_reference:
                update(item,pilot_health=pilot_health(directory,args.pilot_reference,name,
                    item['status'],args.stop_new_model_requests))
            # Persist terminal design state BEFORE attempting an NFS archive.
            if args.archive_root:
                # Preserve sources, witnesses, usage, logs and coverage databases.
                # Rebuildable compiler caches are not required for the archive.
                try:
                    update(item,storage_status='archiving')
                    archive_design(directory,args.archive_root/name,dict(item),args.relocate_completed)
                    update(item,archive=str(args.archive_root/name),
                           storage_status='relocated' if args.relocate_completed else 'verified',
                           storage_finished_utc=utc(),total_elapsed_seconds=time.monotonic()-started)
                except Exception as error:
                    update(item,archive_error=str(error),storage_status='failed_local_retained')
                    return f'{name}: archival failed; local data retained: {error}'
        return None

    def admit(active):
        if args.archive_root:
            from experiment_storage import require_space
            require_space(args.out, minimum=(active+1)*1024*1024*1024)

    try:
        pending, stopped = bounded_designs(args.designs,experiment,args.jobs,admit)
        for name in pending:
            update(progress['designs'][name],status='not_started',reason=stopped)
        if stopped:
            progress['storage_stop_reason'] = stopped
        progress['status'] = ('storage_blocked' if stopped else 'finished_with_failures' if any(
            d['status']=='failed' for d in progress['designs'].values()) else 'finished')
    except BaseException:
        progress['status'] = 'interrupted'
        raise
    finally:
        progress.update(finished_utc=utc(),elapsed_seconds=time.monotonic()-began)
        save(args.out/'progress.json',progress)
        save(args.out/'summary.json',progress)
        if args.archive_root:
            save(args.archive_root/'progress.json',progress)
            save(args.archive_root/'summary.json',progress)


if __name__ == '__main__':
    main()
